REQUIRED_FIELDS = ["mental_health_index", "main_emotion", "triggers", "analysis", "recommendation"]


def run_tests():
    print("=" * 60)
    print(f"Запуск тестирования: {datetime.now().strftime('%d.%m.%Y %H:%M:%S')}")
    print(f"Всего тестовых кейсов: {len(TEST_CASES)}")
    print("=" * 60)

    results = []
    valid_count = 0
    fallback_count = 0
    error_count = 0
    total_time = 0

    for case in TEST_CASES:
        start = time.time()
        try:
            response = requests.post(
                API_URL,
                headers={"Content-Type": "application/json"},
                json={"diary": case["text"]},
                timeout=90
            )
            elapsed = time.time() - start
            total_time += elapsed

            if response.status_code != 200:
                status = "HTTP_ERROR"
                error_count += 1
                note = f"HTTP {response.status_code}"
            else:
                data = response.json()
                missing = [f for f in REQUIRED_FIELDS if f not in data]
                if missing:
                    status = "STRUCTURE_FAIL"
                    error_count += 1
                    note = f"Отсутствуют поля: {missing}"
                else:
                    is_fallback = (
                        data.get("analysis") == "Попробуйте ещё раз" or
                        data.get("analysis") == "Недостаточно данных для анализа" or
                        data.get("triggers") == "Не удалось определить"
                    )
                    if is_fallback:
                        status = "FALLBACK"
                        fallback_count += 1
                        note = "Сработал fallback"
                    else:
                        status = "OK"
                        valid_count += 1
                        note = f"score={data['mental_health_index']}, emotion={data['main_emotion']}"

            results.append({
                "id": case["id"], "category": case["category"],
                "status": status, "time": round(elapsed, 2), "note": note
            })
            print(f"[{case['id']:03d}] {status:15s} {elapsed:5.2f}s  {case['category']}")

        except Exception as e:
            elapsed = time.time() - start
            total_time += elapsed
            error_count += 1
            results.append({
                "id": case["id"], "category": case["category"],
                "status": "EXCEPTION", "time": round(elapsed, 2), "note": str(e)
            })
            print(f"[{case['id']:03d}] EXCEPTION       {elapsed:5.2f}s  {e}")

    total = len(TEST_CASES)
    success_rate = round(valid_count / total * 100, 1)
    structure_validity = round((valid_count + fallback_count) / total * 100, 1)
    avg_time = round(total_time / total, 2)

    print("=" * 60)
    print("ИТОГИ")
    print("=" * 60)
    print(f"Всего тестов:            {total}")
    print(f"Успешно (OK):            {valid_count}")
    print(f"Fallback (API-ошибка):   {fallback_count}")
    print(f"Ошибки:                  {error_count}")
    print(f"Успешность:              {success_rate}%")
    print(f"Валидность структуры:    {structure_validity}%")
    print(f"Среднее время ответа:    {avg_time} сек")
    print("=" * 60)

    report = {
        "timestamp": datetime.now().strftime("%d.%m.%Y %H:%M:%S"),
        "total": total, "valid": valid_count, "fallback": fallback_count,
        "errors": error_count, "success_rate": success_rate,
        "structure_validity": structure_validity,
        "avg_response_time": avg_time, "results": results
    }
    with open("test_report.json", "w", encoding="utf-8") as f:
        json.dump(report, f, ensure_ascii=False, indent=2)
    print("Отчёт сохранён: test_report.json")


if __name__ == "__main__":
    run_tests()